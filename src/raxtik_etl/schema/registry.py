def get_entity_fields(entity: str) -> List[FieldRegistryEntry]:
    """Retrieve all fields registered for a specific canonical entity."""
    return [e for e in SCHEMA_REGISTRY if e.entity == entity]


def get_signature_mapping(signature_id: str, entity: str) -> Dict[str, str]:
    """Return a mapping of source_field -> canonical_field for a signature."""
    mapping = {}
    attr_name = f"{signature_id.lower()}_source_field"
    for entry in get_entity_fields(entity):
        source_field = getattr(entry, attr_name, None)
        if source_field:
            mapping[source_field.lower()] = entry.field_name
    return mapping
